"""Writes docs/API.md from the app's OpenAPI schema. Run: python scripts/gen_api_doc.py [--check].

--check exits 1 when the committed file is out of date (a test and CI use it), so the API reference
can never drift from the code.
"""

import sys
import tempfile
from pathlib import Path

from cpm.api.app import create_app
from cpm.config import Settings
from cpm.security.secrets_store import MemorySecretStore

OUT = Path(__file__).resolve().parents[1] / "docs" / "API.md"
HEAD = """# API reference (generated)

Generated by `python scripts/gen_api_doc.py` from the app's OpenAPI schema; do not edit by hand
(`tests/e2e/test_api_doc.py` fails when it is out of date). The interactive docs page is disabled on
purpose (docs/THREATS.md). Every `/api` call needs the install token (`X-CPM-Token`) and, for
POST/PUT/PATCH/DELETE, the CSRF header (`X-CPM-CSRF`) and a same-origin `Origin`;
see docs/SECURITY.md.
Live streams use WebSockets with a one-time ticket (`/api/runs/{{id}}/stream`).

| Method | Path | Summary |
|---|---|---|
"""


def render() -> str:
    with tempfile.TemporaryDirectory() as d:
        settings = Settings(
            host="127.0.0.1", port=8765, data_dir=Path(d) / "data", log_level="ERROR"
        )
        app = create_app(settings, secret_store=MemorySecretStore())
        paths = app.openapi()["paths"]
    rows = []
    for path in sorted(paths):
        for method in ("get", "post", "put", "patch", "delete"):
            op = paths[path].get(method)
            if op:
                summary = (op.get("summary") or "").replace("|", "/")
                rows.append(f"| {method.upper()} | `{path}` | {summary} |")
    return HEAD.replace("{{", "{").replace("}}", "}") + "\n".join(rows) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({text.count(chr(10))} lines)")
